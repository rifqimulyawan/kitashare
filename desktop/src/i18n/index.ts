const savedLang = localStorage.getItem("kitashare-lang") || "id";

i18n.use(initReactI18next).init({
  resources,
  lng: savedLang,
  fallbackLng: "en",
  interpolation: { escapeValue: false },
});

export const languages = [
  { code: "en", label: "English", native: "English", dir: "ltr" },
  { code: "id", label: "Indonesian", native: "Bahasa Indonesia", dir: "ltr" },
  { code: "ar", label: "Arabic", native: "العربية", dir: "rtl" },
];

export function changeLanguage(lang: string) {
  i18n.changeLanguage(lang);
  localStorage.setItem("kitashare-lang", lang);
  const dir = languages.find((l) => l.code === lang)?.dir || "ltr";
  document.documentElement.dir = dir;
  document.documentElement.lang = lang;
}

const initDir = languages.find((l) => l.code === savedLang)?.dir || "ltr";
document.documentElement.dir = initDir;
document.documentElement.lang = savedLang;

export default i18n;
